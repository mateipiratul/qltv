REM **********************************************************************************
REM este creat tabelul REGIUNI pentru a retine informatii despre regiuni pentru tari *
REM tabelul TARI are o cheie externa catre acest tabel                               *
REM **********************************************************************************
PROMPT ****** creating REGIUNI table...

CREATE TABLE regiuni (
    id_regiune   VARCHAR2(2),
    nume_regiune VARCHAR2(40),

    CONSTRAINT pk_regiune PRIMARY KEY (id_regiune)
);


REM ******************************************************
REM este creat tabelul TARI pentru a retine informatii   *
REM despre tari ale membrilor si, implicit, echipe       *
REM tabelul MEMBRI are o cheie externa catre acest tabel *
REM ******************************************************
PROMPT ****** creating TARI table...

CREATE TABLE tari (
    id_tara    VARCHAR2(2),
    id_regiune VARCHAR2(2) NOT NULL,
    nume_tara  VARCHAR2(60),
    steag_url  VARCHAR2(255),

    CONSTRAINT pk_tara PRIMARY KEY (id_tara),
    CONSTRAINT fk_tara_regiune FOREIGN KEY (id_regiune)
        REFERENCES regiuni(id_regiune) ON DELETE CASCADE
);


REM ***********************************************************************
REM este creat tabelul TIPURI_EVENIMENT pentru a retine informatii despre *
REM magnitudinea turneului organizat si natura acestuia                   *
