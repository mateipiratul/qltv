    nume_rol VARCHAR2(25),

    CONSTRAINT pk_rol PRIMARY KEY (id_rol)
);


REM *****************************************************************************
REM este creat tabelul HARTI pentru a retine informatii despre setul de harti   *
REM valabil in joc si care dintre acestea sunt jucate activ la nivel competitiv *
REM tabelul INSTANTE_MECI_HARTA are o cheie externa catre acest tabel           *
REM *****************************************************************************
PROMPT ****** creating HARTI table...

CREATE TABLE harti (
    id_harta NUMBER GENERATED BY DEFAULT ON NULL
        AS IDENTITY (START WITH 10000 CACHE 20 NOORDER),
    nume_harta VARCHAR2(30),
    pool_activ NUMBER(1) DEFAULT 0 NOT NULL,
    imagine_url VARCHAR2(255),

    CONSTRAINT pk_harta PRIMARY KEY (id_harta),
    CONSTRAINT chk_pool_activ CHECK (pool_activ IN (0, 1))
);


REM ************************************************************
REM este creat tabelul ORGANIZATORI pentru a retine informatii *
REM despre corpurile logistice ce se ocupa de evenimente       *
REM tabelul TURNEE are o cheie externa catre acest tabel       *
REM ************************************************************
PROMPT ****** creating ORGANIZATORI table...

CREATE TABLE organizatori (
    id_organizator NUMBER GENERATED BY DEFAULT ON NULL
        AS IDENTITY (START WITH 200000 CACHE 20 NOORDER),
    nume_organizator VARCHAR2(40),
    site_web         VARCHAR2(100),
    email_contact    VARCHAR2(50),
    logo_url         VARCHAR2(255),

    CONSTRAINT pk_organizator PRIMARY KEY (id_organizator),
    CONSTRAINT chk_valid_website_org
        CHECK(REGEXP_LIKE(site_web, '^(https?://)?([a-zA-Z0-9.-]+)\.([a-zA-Z]{2,})(/.*)?$')),
    CONSTRAINT chk_valid_email
        CHECK(REGEXP_LIKE(email_contact, '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$'))
);


REM ***************************************************************
REM este creat tabelul SPONSORI pentru a retine informatii despre *
REM corpurile care suporta financiar echipele profesioniste       *
REM tabelul SPONSORIZARI are o cheie externa catre acest tabel    *
REM ***************************************************************
PROMPT ****** creating SPONSORI table...

CREATE TABLE sponsori (
