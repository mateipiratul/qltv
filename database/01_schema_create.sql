REM ***********************************************************************
PROMPT ****** creating TIPURI_EVENIMENT table...

CREATE TABLE tipuri_eveniment (
    id_tip_eveniment VARCHAR2(2),
    nume_tip         VARCHAR2(20),
    descriere        VARCHAR2(255),

    CONSTRAINT pk_tip_eveniment PRIMARY KEY (id_tip_eveniment)
);


REM *************************************************************
REM este creat tabelul ROLURI pentru a retine informatii despre *
REM rolurile asignate jucatorilor                               *
