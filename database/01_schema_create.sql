REM **************************************************************
REM este creat tabelul ECHIPE pentru a retine informatii despre  *
REM organizatiile ce participa la turnee                         *
REM tabelele SPONSORIZARI, ISTORIC_CONTRACTE si PARTICIPARE_MECI *
REM au chei externe catre acest tabel                            *
REM **************************************************************
PROMPT ****** creating ECHIPE table...

CREATE TABLE echipe (
    id_echipa NUMBER GENERATED BY DEFAULT ON NULL
        AS IDENTITY (START WITH 200000 CACHE 20 NOORDER),
    nume_echipa     VARCHAR2(30),
    tag_echipa      VARCHAR2(5),
    ranking_mondial INTEGER,
    logo_url        VARCHAR2(255),

    CONSTRAINT pk_echipa PRIMARY KEY (id_echipa),
    CONSTRAINT chk_nume_echipa_valid CHECK (LENGTH(nume_echipa) > 1)
);


REM *************************************************************
REM este creat tabelul TURNEE pentru a retine informatii despre *
REM evenimentele tinute la care participa echipele              *
REM tabelul MECIURI are o cheie externe catre acest tabel       *
REM *************************************************************
PROMPT ****** creating TURNEE table...

CREATE TABLE turnee (
    id_turneu NUMBER GENERATED BY DEFAULT ON NULL
        AS IDENTITY (START WITH 200000 CACHE 20 NOORDER),
    id_organizator   NUMBER NOT NULL,
    id_tip_eveniment VARCHAR2(2) NOT NULL,
    nume_turneu      VARCHAR2(40),
    data_inceput     DATE NOT NULL,
    data_sfarsit     DATE,
    locatie_oras     VARCHAR2(40),
    premiu_total_usd NUMBER,

    CONSTRAINT pk_turneu PRIMARY KEY (id_turneu),
    CONSTRAINT fk_organizator FOREIGN KEY (id_organizator)
        REFERENCES organizatori(id_organizator) ON DELETE CASCADE,
    CONSTRAINT fk_tip_eveniment FOREIGN KEY (id_tip_eveniment)
        REFERENCES tipuri_eveniment(id_tip_eveniment) ON DELETE CASCADE,
    CONSTRAINT chk_perioada_valida_turneu CHECK (data_sfarsit >= data_inceput)
);


REM *************************************************************
REM este creat tabelul MEMBRI pentru a retine informatii despre *
REM indivizii ce apartin scenei profesioniste a jocului         *
REM este superclasa pentru JUCATORI si ANTRENORI                *
REM tabelele ISTORIC_CONTRACTE, STATISTICI_INDIVIDUALE          *
REM au chei externe catre acest tabel                           *
REM *************************************************************
PROMPT ****** creating MEMBRI table...

CREATE TABLE membri (
    id_membru NUMBER GENERATED BY DEFAULT ON NULL
        AS IDENTITY (START WITH 200000 CACHE 20 NOORDER),
    id_tara      VARCHAR2(2),
    nume         VARCHAR2(30),
    prenume      VARCHAR2(30),
    nickname     VARCHAR2(25),
    data_nastere DATE,
    poza_profil_url VARCHAR2(255),

    CONSTRAINT pk_membru PRIMARY KEY (id_membru),
    CONSTRAINT fk_tara FOREIGN KEY (id_tara)
        REFERENCES tari(id_tara) ON DELETE SET NULL
