REM ************************************************************************
REM este creat tabelul MECIURI pentru a retine informatii despre disputele *
REM organizate in cadrul evenimentelor dintre echipele participante        *
REM tabelele INSTANTE_MECI_HARTA si PARTICIPAR_MECIURI                     *
REM au chei externe catre acest tabel                                      *
REM ************************************************************************
PROMPT ****** creating MECIURI table...

CREATE TABLE meciuri (
    id_meci NUMBER GENERATED BY DEFAULT ON NULL
        AS IDENTITY (START WITH 200000 CACHE 20 NOORDER),
    id_turneu   NUMBER NOT NULL,
    data_ora    DATE,
    format_meci VARCHAR2(3),
    faza_turneu VARCHAR2(50) DEFAULT 'Group Stage',

    CONSTRAINT pk_meci PRIMARY KEY (id_meci),
    CONSTRAINT fk_turneu FOREIGN KEY (id_turneu)
        REFERENCES turnee(id_turneu) ON DELETE CASCADE,
    CONSTRAINT chk_format CHECK
        (REGEXP_LIKE(format_meci, '^BO[1,3,5]$', 'i')),
    CONSTRAINT chk_faza CHECK 
        (faza_turneu IN ('Final', 'Semi-Final', 'Quarter-Final', 'Group Stage', 'League Match', 'Showmatch'))
);


REM *************************************************************
REM este creat tabelul INSTANTE_MECI_HARTA pentru a fi retinute *
REM informatii despre HARTI jucate in cadrul unor MECIURI       *
REM tabelul RUNDE are o cheie externa catre acest tabel         *
REM *************************************************************
PROMPT ****** creating INSTANTE_MECI_HARTA table...

CREATE TABLE instante_meci_harta (
    id_instanta NUMBER GENERATED BY DEFAULT ON NULL
        AS IDENTITY (START WITH 200000 CACHE 20 NOORDER),
    id_meci       NUMBER NOT NULL,
    id_harta      NUMBER NOT NULL,
    durata_minute INTEGER,

    CONSTRAINT pk_instanta PRIMARY KEY (id_instanta),
    CONSTRAINT fk_meci_instanta FOREIGN KEY (id_meci)
        REFERENCES meciuri(id_meci) ON DELETE CASCADE,
    CONSTRAINT fk_harta FOREIGN KEY (id_harta)
        REFERENCES harti(id_harta) ON DELETE CASCADE
);


REM *****************************************************************************
REM este creat tabelul RUNDE pentru a retine informatii cu privire la contextul *
REM detaliat din cadrul unei instante a unui meci desfasurat pe o harta         *
REM tabelul STATISTICI_INDIVIDUALE are o cheie externa catre acest tabel        *
REM *****************************************************************************
REM **** EXPLICATIE CODURI REZULTATE ****
REM TRCT - Time Ran Out   (Victorie CT) *
REM ELCT - Elimination CT (Victorie CT) *
REM ELT  - Elimination T  (Victorie T)  *
REM BDCT - Bomb Defused   (Victorie CT) *
REM BET  - Bomb Exploded  (Victorie T)  *
REM *************************************
PROMPT ****** creating RUNDE table...

CREATE TABLE runde (
    id_runda NUMBER GENERATED BY DEFAULT ON NULL
        AS IDENTITY (START WITH 200000 CACHE 20 NOORDER),
    id_instanta  NUMBER NOT NULL,
    numar_runda  INTEGER NOT NULL,
    cod_rezultat VARCHAR2(4) NOT NULL,

    CONSTRAINT pk_runda PRIMARY KEY (id_runda),
    CONSTRAINT fk_instanta FOREIGN KEY (id_instanta)
        REFERENCES instante_meci_harta(id_instanta) ON DELETE CASCADE,
    CONSTRAINT chk_valid_round CHECK (numar_runda > 0),
    CONSTRAINT chk_cod_rezultat CHECK (cod_rezultat IN ('TRCT', 'ELCT', 'ELT', 'BDCT', 'BET'))
);


REM *******************************************************
REM este creat tabelul NOUTATI pentru a retine informatii *
REM despre evenimentele profesioniste organizate          *
REM *******************************************************
PROMPT ****** creating NOUTATI table...

CREATE TABLE noutati (
    id_noutate   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 10000 CACHE 20 NOORDER),
    titlu_noutate    VARCHAR2(100),
    continut_noutate CLOB,
    data_postare     DATE,
    imagine_url      VARCHAR2(255),

    CONSTRAINT pk_noutate PRIMARY KEY (id_noutate)
);

REM **************************************************************
REM este creat tabelul UTILIZATORI pentru a retine informatii    *
REM despre utilizatorii care au acces la aplicatie profesionista *
REM **************************************************************
PROMPT ****** creating UTILIZATORI table...

CREATE TABLE utilizatori (
    id_user NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 10000 CACHE 20 NOORDER),
    email           VARCHAR2(100) UNIQUE NOT NULL,
    parola_hash     VARCHAR2(255) NOT NULL,
    username        VARCHAR2(50) UNIQUE NOT NULL,
    tip_user        VARCHAR2(10) DEFAULT 'STANDARD' NOT NULL,
    data_creare     DATE DEFAULT SYSDATE NOT NULL,
    nationalitate   VARCHAR2(2),
    poza_profil_url VARCHAR2(255),
    este_activ      NUMBER(1) DEFAULT 1 NOT NULL,

    CONSTRAINT pk_utilizatori PRIMARY KEY (id_user),
    CONSTRAINT fk_utilizatori_nat FOREIGN KEY (nationalitate) REFERENCES tari(id_tara) ON DELETE SET NULL,
    CONSTRAINT chk_utilizatori_email CHECK (REGEXP_LIKE(email, '^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$')),
    CONSTRAINT chk_utilizatori_user CHECK (LENGTH(username) > 1),
    CONSTRAINT chk_utilizatori_type CHECK (tip_user IN ('ADMIN', 'STANDARD')),
    CONSTRAINT chk_utilizatori_active CHECK (este_activ IN (0, 1))
    );


REM *************************************************************
REM este creat tabelul COMENTARII pentru a retine feedback-ul   *
REM utilizatorilor pe noutati, in mod ierarhic (tree structure) *
REM *************************************************************
PROMPT ****** creating COMENTARII table...

CREATE TABLE comentarii (
    id_comentariu NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH 10000 CACHE 20 NOORDER),
    id_noutate    NUMBER NOT NULL,
    id_user       NUMBER NOT NULL,
    id_parinte    NUMBER,
    continut      VARCHAR2(1000) NOT NULL,
    data_postare  DATE DEFAULT SYSDATE NOT NULL,

    CONSTRAINT pk_comentarii PRIMARY KEY (id_comentariu),
    CONSTRAINT fk_comentarii_news FOREIGN KEY (id_noutate)
        REFERENCES noutati(id_noutate) ON DELETE CASCADE,
    CONSTRAINT fk_comentarii_user FOREIGN KEY (id_user)
        REFERENCES utilizatori(id_user) ON DELETE CASCADE,
    CONSTRAINT fk_comentarii_parent FOREIGN KEY (id_parinte)
        REFERENCES comentarii(id_comentariu) ON DELETE CASCADE,
    CONSTRAINT chk_comentarii_cont CHECK (LENGTH(continut) > 0)
);


